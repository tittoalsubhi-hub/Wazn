"""Generates values/strings.xml and values-ar/strings.xml from strings_data.py (run from repo root)."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from strings_data import rows
def esc(t):
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'").replace('"', '\\"')
    return t
def write(path, idx):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_strings.py — edit tools/strings_data.py -->\n<resources>\n')
        for r in rows():
            f.write(f'    <string name="{r[0]}">{esc(r[idx])}</string>\n')
        f.write("</resources>\n")
write("app/src/main/res/values/strings.xml", 1)
write("app/src/main/res/values-ar/strings.xml", 2)
print("ok", sum(1 for _ in rows()))
